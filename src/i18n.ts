const dictionaries: Record<Language, Record<MessageKey, string>> = { ru, en };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Language): Translate {
  const dict = dictionaries[lang] ?? ru;
  return (key, vars) => {
    let s: string = dict[key] ?? ru[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export const I18n = createContext<{ t: Translate; lang: Language }>({ t: makeT("ru"), lang: "ru" });
export const useI18n = () => useContext(I18n);
